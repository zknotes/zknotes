/** The icons and accent colours for the encFile / share file chip — one place of truth. */

export const ARCHIVE_EXTS = ["ZIP", "TAR", "GZ", "RAR", "7Z", "BZ2"];

export function fileExtLabel(name: string): string {
    return (name.includes(".") ? name.split(".").pop()?.toUpperCase() : null) ?? "FILE";
}

export type FileChipIconState = {
    isError?: boolean;
    isDeleted?: boolean;
};

export function getFileChipIconSvg(
    mime: string | null | undefined,
    ext: string,
    state: FileChipIconState = {},
): string {
    const { isError = false, isDeleted = false } = state;
    if (isError)
        return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="10"/><line x1="12" y1="8" x2="12" y2="12"/><line x1="12" y1="16" x2="12.01" y2="16"/></svg>`;
    if (isDeleted)
        return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><polyline points="14 2 14 8 20 8"/><line x1="9.5" y1="12.5" x2="14.5" y2="17.5"/><line x1="14.5" y1="12.5" x2="9.5" y2="17.5"/></svg>`;
    if (mime?.startsWith("video/"))
        return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><polygon points="23 7 16 12 23 17 23 7"/><rect x="1" y="5" width="15" height="14" rx="2" ry="2"/></svg>`;
    if (mime?.startsWith("audio/"))
        return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M9 18V5l12-2v13"/><circle cx="6" cy="18" r="3"/><circle cx="18" cy="16" r="3"/></svg>`;
    if (mime === "application/pdf" || ext === "PDF")
        return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><polyline points="14 2 14 8 20 8"/><line x1="16" y1="13" x2="8" y2="13"/><line x1="16" y1="17" x2="8" y2="17"/><polyline points="10 9 9 9 8 9"/></svg>`;
    if (ARCHIVE_EXTS.includes(ext))
        return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><polyline points="21 8 21 21 3 21 3 8"/><rect x="1" y="3" width="22" height="5"/><line x1="10" y1="12" x2="14" y2="12"/></svg>`;
    return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><polyline points="14 2 14 8 20 8"/></svg>`;
}

export function getFileChipAccentClasses(
    mime: string | null | undefined,
    ext: string,
    state: FileChipIconState = {},
): string {
    const { isError = false, isDeleted = false } = state;
    if (isError) return "bg-red-900/30 text-red-400 border-red-800/40";
    if (isDeleted)
        return "bg-[color-mix(in_srgb,var(--surface-raised)_50%,transparent)] text-[var(--text-muted)] border-[color-mix(in_srgb,var(--stroke)_50%,transparent)]";
    if (mime?.startsWith("video/")) return "bg-purple-900/30 text-purple-400";
    if (mime?.startsWith("audio/")) return "bg-green-900/30 text-green-400";
    if (mime === "application/pdf" || ext === "PDF") return "bg-red-900/30 text-red-400";
    if (ARCHIVE_EXTS.includes(ext)) return "bg-yellow-900/30 text-yellow-400";
    return "bg-blue-900/30 text-blue-400";
}

